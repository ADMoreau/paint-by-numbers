"""Write paint_by_numbers/data/spectral_bands.json: the wavelength bands the paint model works in.

Build time only (needs colour-science: pip install -e ".[liquitex]"). The planner and the phone app
read the JSON, so neither needs colour-science.

    python scripts/make_spectral_bands.py

Paint reflectance is modeled in BANDS bands across the visible spectrum, each WIDTH nm wide
(centres 400, 430, ... 700 nm; the first and last bands extend to 380 and 730 nm). The file holds:

- ``to_xyz`` (3 x N): reflectance in each band -> CIE XYZ under illuminant D65 with the 2 degree
  observer, from the 5 nm tables summed over each band. Rows are scaled so reflectance 1 in every
  band is exactly the D65 white the rest of the code uses (Y = 1), so a flat spectrum is a neutral.
- ``from_xyz`` (N x 3): the smoothest spectrum with a given XYZ (least squared second differences,
  so a neutral comes out flat), used to turn colors (a background, a published paint color)
  into spectra. ``to_xyz @ from_xyz`` is the identity.

It also writes the same tables as Kotlin constants for the phone planner (planner/Bands.kt).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paint_by_numbers" / "data" / "spectral_bands.json"
KOTLIN = ROOT / "android/app/src/main/java/io/github/admoreau/paintbynumbers/planner/Bands.kt"
FIRST, LAST, WIDTH = 400, 700, 30
WHITE_XYZ = np.array([0.4124564 + 0.3575761 + 0.1804375, 1.0, 0.0193339 + 0.1191920 + 0.9503041])  # color._WHITE_XYZ


def main() -> int:
    import colour

    fine = colour.SpectralShape(380, 730, 5)
    cmfs = colour.MSDS_CMFS["CIE 1931 2 Degree Standard Observer"].copy().align(fine)
    d65 = colour.SDS_ILLUMINANTS["D65"].copy().align(fine)
    wf = np.arange(380, 731, 5)
    weights = cmfs.values * d65.values[:, None]  # (fine, 3)

    centres = np.arange(FIRST, LAST + 1, WIDTH)
    edges = np.concatenate([[380.0], (centres[:-1] + centres[1:]) / 2, [731.0]])
    to_xyz = np.stack([weights[(wf >= lo) & (wf < hi)].sum(axis=0) for lo, hi in zip(edges[:-1], edges[1:])]).T  # (3, N)
    to_xyz *= (WHITE_XYZ / to_xyz.sum(axis=1))[:, None]  # flat reflectance 1 -> the white point exactly

    n = len(centres)
    d2 = np.diff(np.eye(n), n=2, axis=0)  # second differences; flat and straight spectra cost nothing
    # minimize |d2 r|^2 subject to to_xyz r = xyz, by its KKT system: linear in xyz, so a fixed matrix
    kkt = np.block([[2 * d2.T @ d2, to_xyz.T], [to_xyz, np.zeros((3, 3))]])
    from_xyz = np.linalg.solve(kkt, np.vstack([np.zeros((n, 3)), np.eye(3)]))[:n]
    assert np.allclose(to_xyz @ from_xyz, np.eye(3), atol=1e-9)
    assert np.allclose(from_xyz @ WHITE_XYZ, 1.0, atol=1e-6), "white should map to a flat spectrum"
    OUT.write_text(json.dumps({
        "about": "Bands of the paint model's spectral reflectance; see scripts/make_spectral_bands.py",
        "illuminant": "D65", "observer": "CIE 1931 2 degree",
        "centres_nm": centres.tolist(), "edges_nm": edges.tolist(),
        "to_xyz": to_xyz.tolist(), "from_xyz": from_xyz.tolist(),
    }, indent=1) + "\n")
    def kt(values) -> str:
        return ",\n        ".join(", ".join(repr(float(v)) for v in row) for row in np.atleast_2d(values))

    KOTLIN.write_text(f"""package io.github.admoreau.paintbynumbers.planner

// Generated by scripts/make_spectral_bands.py from paint_by_numbers/data/spectral_bands.json. Don't edit.

/** The paint model's wavelength bands (see color.py's working space). */
object Bands {{
    const val N = {n}
    val CENTRES_NM = intArrayOf({", ".join(str(int(c)) for c in centres)})

    /** Reflectance per band to CIE XYZ (D65, 2 degree observer), 3 x N row-major. */
    val TO_XYZ = doubleArrayOf(
        {kt(to_xyz)},
    )

    /** CIE XYZ to the smoothest spectrum with that colour, N x 3 row-major. */
    val FROM_XYZ = doubleArrayOf(
        {kt(from_xyz)},
    )
}}
""")
    print(f"wrote {OUT.relative_to(ROOT)} and {KOTLIN.relative_to(ROOT)}: {n} bands of {WIDTH} nm, centres {centres[0]}-{centres[-1]} nm")
    return 0


if __name__ == "__main__":
    sys.exit(main())
